export const RULE_IDS = RULES.map((r) => r[0]);

export function classifyMaterial(p) {
  // 괄호와 "…일원"(구역 표기)을 떼고 판단한다. "일원"의 '원'이 건물 접미사(院)로 오인되지 않게 하기 위함
  const full = p.국가유산명.trim().replace(/\(.*?\)|<.*?>/g, "").trim().replace(/\s*일원$/, "");
  const head = headOf(full);
  const last = head.split(/\s+/).pop();
  const lastFull = full.split(/\s+/).pop();
  for (const [id, material, target, re] of RULES) {
    const m = target === "either" ? (last.match(re) ?? lastFull.match(re)) : (target === "last" ? last : full).match(re);
    if (m) return { material, rule: id, matched: m[0] };
  }
  return { material: null, rule: "no-rule", matched: "" };
}
